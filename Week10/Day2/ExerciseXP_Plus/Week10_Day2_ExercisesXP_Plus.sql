-- SELECT 1: all columns, all students
SELECT * FROM public.students ORDER BY id;

-- SELECT 2: first and last names only
SELECT first_name, last_name FROM public.students ORDER BY id;

-- SELECT 3.1: student with ID 2
SELECT first_name, last_name FROM public.students WHERE id = 2;

-- SELECT 3.2: last name Benichou AND first name Marc
SELECT first_name, last_name FROM public.students
WHERE last_name = 'Benichou' AND first_name = 'Marc';

-- SELECT 3.3: last name Benichou OR first name Marc
SELECT first_name, last_name FROM public.students
WHERE last_name = 'Benichou' OR first_name = 'Marc';

-- SELECT 3.4: first names containing a (case-insensitive)
SELECT first_name, last_name FROM public.students WHERE first_name ILIKE '%a%';

-- SELECT 3.5: first names starting with a
SELECT first_name, last_name FROM public.students WHERE first_name ILIKE 'a%';

-- SELECT 3.6: first names ending with a
SELECT first_name, last_name FROM public.students WHERE first_name ILIKE '%a';

-- SELECT 3.7: second-to-last letter of first name is a
SELECT first_name, last_name FROM public.students WHERE first_name ILIKE '%a_';

-- SELECT 3.8: students with IDs 1 AND 3 (i.e., both IDs in the result)
SELECT first_name, last_name FROM public.students WHERE id IN (1, 3);

-- SELECT 4: all columns for students born on or after January 1, 2000
SELECT * FROM public.students WHERE birth_date >= DATE '2000-01-01' ORDER BY birth_date;

